def F(code, desc, sev, causes, actions, parts, mttr, w, trade, src="synthetic", sig=None):
    """Fault definition.
    sev 1=minor 2=moderate 3=major 4=critical(safety/line-down)
    mttr = (min, max) minutes ; w = relative frequency weight
    sig = (sensor_name, shape) so the simulator can inject a matching signature
    """
    return dict(code=code, desc=desc, sev=sev, causes=causes, actions=actions, parts=parts,
                mttr=mttr, w=w, trade=trade, source=src, sig=sig)


def PM(pid, task, hours=None, days=None, dur=60, trade="MECH", skill="L1", steps=None, parts=None):
    return dict(id=pid, task=task, interval_hours=hours, interval_days=days, duration_min=dur,
                trade=trade, skill=skill, steps=steps or [], parts=parts or [])


def S(name, unit, nominal, sigma, warn, alarm):
    return dict(name=name, unit=unit, nominal=nominal, sigma=sigma, warn=warn, alarm=alarm)


